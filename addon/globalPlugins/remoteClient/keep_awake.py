"""Prevent the controlled computer from going to sleep while it is left unattended.

When Windows has seen no keyboard or mouse input for a configurable delay, the
system idle timers are reset and an F15 key press (a key which does nothing on
Windows) is injected, so that neither the screen saver nor the lock screen kicks
in. The key is injected while NVDA is told to ignore injected input: NVDA never
sees it, so it is not announced in input help, not reported as a command key, not
shown in braille, and nothing about it reaches the controlling computer. The
speech of this computer is never touched.

Keys and mouse moves sent by the controlling computer are injected locally, so
Windows counts them as input like any other. Activity which Windows does not see
but which shows that the computer is in use (speech, gestures from a braille
display, a file transfer, screen or audio sharing) restarts the optional maximum
duration, exactly like a key press does.
"""

import contextlib
import ctypes
from ctypes import wintypes
import time

import speech
import wx
from logHandler import log

from . import configuration

VK_F15 = 0x7E
KEYEVENTF_KEYUP = 0x0002
MAPVK_VK_TO_VSC = 0
ES_SYSTEM_REQUIRED = 0x00000001
ES_DISPLAY_REQUIRED = 0x00000002

# Minimum delay, in seconds, between two idle checks.
_MIN_CHECK_INTERVAL_SECONDS = 1
# Ignore hook notifications caused by the injected key for this short period.
_KEEP_AWAKE_INPUT_IGNORE_SECONDS = 0.5
# Raw key events may reach NVDA shortly after keybd_event returns. Keep the
# suppression bounded so that a physical F15 press is not hidden later.
_INJECTED_KEY_SUPPRESSION_SECONDS = 1
# Available maximum durations, in minutes. Zero means no limit.
KEEP_AWAKE_MAX_DURATION_MINUTES = (30, 60, 120, 240, 480, 0)


class LASTINPUTINFO(ctypes.Structure):
	_fields_ = [
		("cbSize", wintypes.UINT),
		("dwTime", wintypes.DWORD),
	]


def get_system_idle_seconds():
	"""Return the number of seconds since the last system wide keyboard or mouse input."""
	info = LASTINPUTINFO()
	info.cbSize = ctypes.sizeof(info)
	if not ctypes.windll.user32.GetLastInputInfo(ctypes.byref(info)):
		return 0.0
	elapsed = (ctypes.windll.kernel32.GetTickCount() - info.dwTime) / 1000.0
	# GetTickCount wraps around after about 49 days. Treat a negative result as no idle time.
	return elapsed if elapsed > 0 else 0.0


_injection_bypass_reported = False


def _ignore_injection():
	"""Return a context manager under which NVDA ignores the keys this add-on injects."""
	global _injection_bypass_reported
	try:
		from .remote_keyboard import ignore_injection

		return ignore_injection()
	except Exception:
		if not _injection_bypass_reported:
			_injection_bypass_reported = True
			log.exception("NVDA cannot be told to ignore the injected key; it may announce F15")
		return contextlib.nullcontext()


class KeepAwake:
	"""Injects an F15 key press when the machine has been left unattended."""

	def __init__(self, is_active=None, current_activity=None):
		self._last_speech = None
		self._last_gesture = None
		self._speech_hooked = False
		self._gestures_hooked = False
		self._timer = None
		self._is_active = is_active or (lambda: True)
		#: Returns the name of what keeps this computer busy besides speech and
		#: gestures (a file transfer, a shared screen...), or None.
		self._current_activity = current_activity or (lambda: None)
		self._last_local_input = time.monotonic()
		self._prevention_started = None
		self._prevention_expired = False
		self._ignore_input_until = 0.0
		self._injected_key_events_remaining = 0
		self._injected_key_suppression_until = 0.0

	def consume_injected_key(self, vk_code):
		"""Return true for an F15 event generated by this keep-awake instance.

		Second safety net, for the case where NVDA could not be told to ignore the
		injected key: the raw key handler drops the event before NVDA treats it as a
		gesture.
		"""
		if vk_code != VK_F15 or self._injected_key_events_remaining <= 0:
			return False
		if time.monotonic() > self._injected_key_suppression_until:
			self._injected_key_events_remaining = 0
			return False
		self._injected_key_events_remaining -= 1
		return True

	def notify_local_input(self, from_keep_awake=False):
		"""Record activity reported by the add-on keyboard and mouse hooks."""
		now = time.monotonic()
		self._last_local_input = now
		if from_keep_awake or now < self._ignore_input_until:
			return
		self._prevention_started = None
		if self._prevention_expired:
			# The user came back: the maximum duration starts again the next time
			# the computer is left alone. Hooks run on their own threads.
			self._prevention_expired = False
			wx.CallAfter(self.reload)

	def notify_speech(self, **kwargs):
		"""Record that NVDA was just asked to say something."""
		self._last_speech = time.monotonic()

	def notify_gesture(self, gesture=None, **kwargs):
		"""Record a gesture executed by NVDA, whatever its source (keyboard, braille display, touch).

		Registered on an NVDA decider, hence the mandatory True return value.
		"""
		self._last_gesture = time.monotonic()
		return True

	def _activity(self, delay):
		"""Return the name of what keeps the computer busy without any system input, or None."""
		now = time.monotonic()
		if self._last_gesture is not None and now - self._last_gesture < delay:
			return "a braille or other NVDA gesture"
		if self._last_speech is not None and now - self._last_speech < delay:
			return "speech"
		try:
			from speech.sayAll import SayAllHandler

			if SayAllHandler.isRunning():
				return "say all"
		except Exception:
			pass
		try:
			return self._current_activity() or None
		except Exception:
			log.exception("Unable to determine whether the computer is busy")
			return None

	def _hook_speech(self):
		if self._speech_hooked:
			return
		pre_speech = getattr(getattr(speech, "extensions", None), "pre_speech", None)
		if pre_speech is None:
			return
		pre_speech.register(self.notify_speech)
		self._speech_hooked = True

	def _unhook_speech(self):
		if not self._speech_hooked:
			return
		self._speech_hooked = False
		try:
			speech.extensions.pre_speech.unregister(self.notify_speech)
		except Exception:
			log.exception("Unable to stop following speech")

	def _hook_gestures(self):
		if self._gestures_hooked:
			return
		try:
			import inputCore

			decider = getattr(inputCore, "decide_executeGesture", None)
		except ImportError:
			decider = None
		if decider is None:
			return
		decider.register(self.notify_gesture)
		self._gestures_hooked = True

	def _unhook_gestures(self):
		if not self._gestures_hooked:
			return
		self._gestures_hooked = False
		try:
			import inputCore

			inputCore.decide_executeGesture.unregister(self.notify_gesture)
		except Exception:
			log.exception("Unable to stop following gestures")

	def start(self):
		self._hook_speech()
		self._hook_gestures()
		self.notify_local_input()
		self._prevention_started = None
		self._prevention_expired = False
		self._schedule()

	def reload(self):
		"""Take the current configuration into account."""
		self._cancel_timer()
		self._prevention_started = None
		self._prevention_expired = False
		self._schedule()

	def stop(self):
		self._cancel_timer()
		self._reset_prevention()
		self._unhook_gestures()
		self._unhook_speech()

	def _reset_prevention(self):
		self._prevention_started = None
		self._prevention_expired = False

	def _cancel_timer(self):
		if self._timer is not None:
			self._timer.Stop()
			self._timer = None

	def _get_settings(self):
		config = configuration.get_config()["keep_awake"]
		max_duration_minutes = int(config.get("max_duration_minutes", 0) or 0)
		if max_duration_minutes not in KEEP_AWAKE_MAX_DURATION_MINUTES:
			max_duration_minutes = 0
		enabled = bool(config["enabled"])
		if enabled:
			try:
				enabled = bool(self._is_active())
			except Exception:
				log.exception("Unable to determine whether keep awake is active")
				enabled = False
		return (
			enabled,
			max(5, int(config["delay_seconds"])),
			max_duration_minutes * 60,
		)

	def _schedule(self, delay_seconds=None):
		try:
			enabled, configured_delay, max_duration = self._get_settings()
		except Exception:
			log.exception("Unable to read the keep awake configuration")
			return
		if not enabled:
			self._reset_prevention()
			return
		if self._prevention_expired:
			return
		now = time.monotonic()
		if delay_seconds is None:
			delay_seconds = configured_delay
		if max_duration and self._prevention_started is not None:
			remaining = max_duration - (now - self._prevention_started)
			if remaining <= 0:
				self._prevention_expired = True
				return
			delay_seconds = min(delay_seconds, remaining)
		delay_seconds = max(_MIN_CHECK_INTERVAL_SECONDS, delay_seconds)
		self._timer = wx.CallLater(int(delay_seconds * 1000), self._check)

	def _check(self):
		self._timer = None
		try:
			enabled, delay, max_duration = self._get_settings()
		except Exception:
			log.exception("Unable to read the keep awake configuration")
			return
		if not enabled:
			self._reset_prevention()
			return
		if self._prevention_expired:
			return
		now = time.monotonic()
		if (
			max_duration
			and self._prevention_started is not None
			and now - self._prevention_started >= max_duration
		):
			self._prevention_expired = True
			log.debug("Stopped preventing the computer from going to sleep after the maximum duration")
			return
		idle = min(get_system_idle_seconds(), now - self._last_local_input)
		if idle < delay:
			self._schedule(delay - idle)
			return
		activity = self._activity(delay)
		if activity:
			# The computer is in use even though Windows saw no input: the maximum
			# duration starts counting again, as after a key press.
			self._prevention_started = None
		self._trigger(delay, activity)
		self._schedule(delay)

	def _trigger(self, delay, activity=None):
		if activity:
			log.debug(
				"Keeping the computer awake, busy with %s but without input for %s seconds"
				% (activity, delay),
			)
		else:
			log.debug("Keeping the computer awake after %s seconds without activity" % delay)
		self.notify_local_input(from_keep_awake=True)
		if self._prevention_started is None:
			self._prevention_started = time.monotonic()
		self._ignore_input_until = time.monotonic() + _KEEP_AWAKE_INPUT_IGNORE_SECONDS
		self._reset_idle_timers()
		self._send_f15()

	def _reset_idle_timers(self):
		"""Tell Windows that the system and the display are in use, without any input."""
		try:
			ctypes.windll.kernel32.SetThreadExecutionState(ES_SYSTEM_REQUIRED | ES_DISPLAY_REQUIRED)
		except Exception:
			log.exception("Unable to reset the system idle timers")

	def _send_f15(self):
		"""Press and release F15 without NVDA noticing it."""
		try:
			user32 = ctypes.windll.user32
			scan_code = user32.MapVirtualKeyW(VK_F15, MAPVK_VK_TO_VSC)
			self._injected_key_events_remaining = 2
			self._injected_key_suppression_until = time.monotonic() + _INJECTED_KEY_SUPPRESSION_SECONDS
			# NVDA's keyboard hook runs synchronously while the events are injected, so
			# the flag set by the context manager is seen for both of them.
			with _ignore_injection():
				user32.keybd_event(VK_F15, scan_code, 0, 0)
				user32.keybd_event(VK_F15, scan_code, KEYEVENTF_KEYUP, 0)
		except Exception:
			log.exception("Unable to send the F15 key")
